import { loadEnv } from 'vite'

/**
 * Serves /firebase-messaging-sw.js with Firebase web config from Vite env.
 * Keeps SW config in sync with VITE_FIREBASE_* (no duplicate hardcoding).
 */
export function firebaseMessagingSwPlugin() {
  const SW_PATH = '/firebase-messaging-sw.js'
  let env = {}

  function buildSwSource(e) {
    const config = {
      apiKey: e.VITE_FIREBASE_API_KEY || '',
      authDomain: e.VITE_FIREBASE_AUTH_DOMAIN || '',
      projectId: e.VITE_FIREBASE_PROJECT_ID || '',
      storageBucket: e.VITE_FIREBASE_STORAGE_BUCKET || '',
      messagingSenderId: e.VITE_FIREBASE_MESSAGING_SENDER_ID || '',
      appId: e.VITE_FIREBASE_APP_ID || '',
      measurementId: e.VITE_FIREBASE_MEASUREMENT_ID || ''
    }
    return `/* Generated by vite firebaseMessagingSwPlugin — do not edit */
importScripts('https://www.gstatic.com/firebasejs/11.6.0/firebase-app-compat.js');
importScripts('https://www.gstatic.com/firebasejs/11.6.0/firebase-messaging-compat.js');
firebase.initializeApp(${JSON.stringify(config)});
firebase.messaging();

self.addEventListener('notificationclick', function (event) {
  event.notification.close();
  var data = event.notification.data || {};
  var path = data.actionUrl || data.click_action || '/';
  if (path.indexOf('/admin') === 0) {
    path = path.replace(/^\\/admin/, '') || '/';
  }
  var targetUrl = /^https?:\\/\\//i.test(path)
    ? path
    : self.location.origin + (path.charAt(0) === '/' ? path : '/' + path);
  event.waitUntil(
    clients.matchAll({ type: 'window', includeUncontrolled: true }).then(function (clientList) {
      for (var i = 0; i < clientList.length; i++) {
        var client = clientList[i];
        if ('focus' in client) {
          if (client.navigate) {
            try { client.navigate(targetUrl); } catch (e) { /* ignore */ }
          }
          return client.focus();
        }
      }
      if (clients.openWindow) return clients.openWindow(targetUrl);
    })
  );
});
`
  }

  return {
    name: 'firebase-messaging-sw',
    configResolved(config) {
      env = loadEnv(config.mode, config.envDir || config.root, 'VITE_')
    },
    configureServer(server) {
      server.middlewares.use((req, res, next) => {
        if (req.url?.split('?')[0] !== SW_PATH) return next()
        res.setHeader('Content-Type', 'application/javascript; charset=utf-8')
        res.setHeader('Service-Worker-Allowed', '/')
        res.end(buildSwSource(env))
      })
    },
    generateBundle() {
      this.emitFile({
        type: 'asset',
        fileName: 'firebase-messaging-sw.js',
        source: buildSwSource(env)
      })
    }
  }
}
