import { loadEnv } from 'vite';

/**
 * Serves /firebase-messaging-sw.js with Firebase web config from Vite env.
 * Keeps SW config in sync with VITE_FIREBASE_* (no duplicate hardcoding).
 */
export function firebaseMessagingSwPlugin() {
  const SW_PATH = '/firebase-messaging-sw.js';
  let env = {};

  function buildSwSource(e) {
    const config = {
      apiKey: e.VITE_FIREBASE_API_KEY || '',
      authDomain: e.VITE_FIREBASE_AUTH_DOMAIN || '',
      projectId: e.VITE_FIREBASE_PROJECT_ID || '',
      storageBucket: e.VITE_FIREBASE_STORAGE_BUCKET || '',
      messagingSenderId: e.VITE_FIREBASE_MESSAGING_SENDER_ID || '',
      appId: e.VITE_FIREBASE_APP_ID || '',
      measurementId: e.VITE_FIREBASE_MEASUREMENT_ID || ''
    };
    const apiBase = String(e.VITE_API_URL || '')
      .trim()
      .replace(/\/+$/, '');
    return `/* Generated by vite firebaseMessagingSwPlugin — do not edit */
/* sw-rev: mobile-push-5 */
importScripts('https://www.gstatic.com/firebasejs/11.6.0/firebase-app-compat.js');
importScripts('https://www.gstatic.com/firebasejs/11.6.0/firebase-messaging-compat.js');
firebase.initializeApp(${JSON.stringify(config)});
var API_BASE = ${JSON.stringify(apiBase)};

self.addEventListener('install', function () { self.skipWaiting(); });
self.addEventListener('activate', function (event) {
  event.waitUntil(self.clients.claim());
});

function parseMaybeJson(value) {
  if (!value) return {};
  if (typeof value === 'string') {
    try { return JSON.parse(value); } catch (e) { return {}; }
  }
  return typeof value === 'object' ? value : {};
}

function notificationPayload(event) {
  var note = event.notification || {};
  var data = parseMaybeJson(note.data);
  var extraLink = data.link || data.click_action || data.actionUrl || '';
  if (data.FCM_MSG) {
    var msg = parseMaybeJson(data.FCM_MSG);
    var inner = parseMaybeJson(msg.data);
    var n = parseMaybeJson(msg.notification);
    var link = (msg.fcmOptions && msg.fcmOptions.link)
      || (msg.fcm_options && msg.fcm_options.link)
      || n.click_action
      || inner.actionUrl
      || inner.click_action
      || inner.link
      || '';
    data = Object.assign({}, data, inner, {
      actionUrl: inner.actionUrl || inner.click_action || inner.link || n.click_action || link || data.actionUrl,
      clickToken: inner.clickToken || inner.pj_click || data.clickToken,
      link: inner.link || link || extraLink
    });
  }
  if (!data.actionUrl) data.actionUrl = data.link || data.click_action || extraLink || '/';
  return data;
}

function tokenFrom(data) {
  var t = data.clickToken || data.click_token || data.pj_click || '';
  if (t) return String(t);
  var url = data.actionUrl || data.click_action || data.link || '';
  var m = String(url).match(/[?&](?:pj_click|clickToken)=([^&]+)/i);
  return m ? decodeURIComponent(m[1]) : '';
}

function uniqueUrls(list) {
  var seen = {};
  var out = [];
  for (var i = 0; i < list.length; i++) {
    var url = list[i];
    if (!url || seen[url]) continue;
    seen[url] = true;
    out.push(url);
  }
  return out;
}

async function reportClick(clickToken) {
  if (!clickToken) return;
  var urls = uniqueUrls([
    self.location.origin + '/api/push-campaigns/click',
    API_BASE ? API_BASE + '/api/push-campaigns/click' : ''
  ]);
  var body = JSON.stringify({ clickToken: clickToken });
  for (var i = 0; i < urls.length; i++) {
    try {
      var res = await fetch(urls[i], {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: body,
        keepalive: true,
        credentials: 'omit',
        mode: 'cors'
      });
      if (res && res.ok) return;
    } catch (e) { /* try next */ }
  }
}

function resolveTargetUrl(path) {
  var raw = String(path || '/').trim() || '/';
  if (raw.indexOf('/admin') === 0) {
    raw = raw.replace(/^\\/admin/, '') || '/';
  }
  try {
    return new URL(raw, self.location.origin).toString();
  } catch (e) {
    if (raw.charAt(0) === '/') return self.location.origin + raw;
    return self.location.origin + '/' + raw;
  }
}

async function openTarget(targetUrl) {
  var clientList = await clients.matchAll({ type: 'window', includeUncontrolled: true });
  var targetOrigin = self.location.origin;
  var destPath = '/';
  try {
    var dest = new URL(targetUrl);
    targetOrigin = dest.origin;
    destPath = dest.pathname + dest.search + dest.hash;
  } catch (e) {}
  for (var i = 0; i < clientList.length; i++) {
    var client = clientList[i];
    var clientOrigin = '';
    var clientPath = '';
    try {
      var cu = new URL(client.url);
      clientOrigin = cu.origin;
      clientPath = cu.pathname + cu.search + cu.hash;
    } catch (e) {}
    if (clientOrigin !== targetOrigin) continue;
    try { await client.focus(); } catch (e) {}
    if (clientPath === destPath) return client;
    if (typeof client.navigate === 'function') {
      try {
        var navigated = await client.navigate(targetUrl);
        if (navigated) return navigated;
      } catch (e) {}
    }
    try {
      client.postMessage({ type: 'push-campaign:open', url: targetUrl });
      return client;
    } catch (e) {}
  }
  if (clients.openWindow) return clients.openWindow(targetUrl);
}

function parsePushEvent(event) {
  var payload = {};
  try {
    payload = event.data ? event.data.json() : {};
  } catch (e) {
    try { payload = { body: event.data ? event.data.text() : '' }; } catch (err) { payload = {}; }
  }
  var n = parseMaybeJson(payload.notification);
  var d = parseMaybeJson(payload.data);
  var inner = parseMaybeJson(payload.FCM_MSG);
  if (inner && (inner.notification || inner.data)) {
    n = Object.assign({}, n, parseMaybeJson(inner.notification));
    d = Object.assign({}, d, parseMaybeJson(inner.data));
  }
  var title = n.title || d.title || 'Notification';
  var body = n.body || d.body || '';
  var icon = n.icon || d.iconUrl || '/favicon.ico';
  var image = n.image || d.imageUrl || undefined;
  var data = Object.assign({}, d, {
    title: title,
    body: body,
    iconUrl: icon,
    imageUrl: image || d.imageUrl || '',
    actionUrl: d.actionUrl || d.click_action || d.link || n.click_action || (payload.fcmOptions && payload.fcmOptions.link) || '/',
    click_action: d.click_action || d.actionUrl || d.link || '',
    link: d.link || d.actionUrl || '',
    clickToken: d.clickToken || d.pj_click || '',
    pj_click: d.pj_click || d.clickToken || ''
  });
  return {
    title: title,
    options: {
      body: body,
      icon: icon,
      image: image,
      data: data,
      tag: d.campaignId ? ('push-campaign-' + d.campaignId) : 'playjuwa-push',
      renotify: true,
      requireInteraction: true,
      silent: false,
      vibrate: [200, 100, 200]
    }
  };
}

async function handlePushEvent(event) {
  var parsed = parsePushEvent(event);
  if (!parsed.title) return;
  /* Always show. Android Chrome often keeps visibilityState=visible while the
     app is in the background, which previously skipped the system banner. */
  return self.registration.showNotification(parsed.title, parsed.options);
}

/* Own the push event so a titled FCM payload still displays when no tab is open.
   Firebase otherwise auto-handles it and onBackgroundMessage skips the title case. */
self.addEventListener('push', function (event) {
  event.stopImmediatePropagation();
  event.waitUntil(handlePushEvent(event));
});

/* Register BEFORE firebase.messaging(). FCM's handler calls stopImmediatePropagation
   and often only focuses an existing tab, so the campaign URL never opens. */
self.addEventListener('notificationclick', function (event) {
  event.stopImmediatePropagation();
  event.notification.close();
  var data = notificationPayload(event);
  var clickToken = tokenFrom(data);
  var targetUrl = resolveTargetUrl(data.actionUrl || data.click_action || data.link || '/');
  if (clickToken && targetUrl.indexOf('pj_click=') === -1) {
    targetUrl += (targetUrl.indexOf('?') >= 0 ? '&' : '?') + 'pj_click=' + encodeURIComponent(clickToken);
  }
  event.waitUntil(Promise.all([
    openTarget(targetUrl),
    reportClick(clickToken)
  ]));
});

var messaging = firebase.messaging();

messaging.onBackgroundMessage(function (payload) {
  var n = (payload && payload.notification) || {};
  var d = (payload && payload.data) || {};
  var title = n.title || d.title || 'Notification';
  var options = {
    body: n.body || d.body || '',
    icon: n.icon || d.iconUrl || '/favicon.ico',
    image: n.image || d.imageUrl || undefined,
    data: Object.assign({}, d, {
      actionUrl: d.actionUrl || d.click_action || d.link || '/',
      clickToken: d.clickToken || d.pj_click || ''
    }),
    tag: d.campaignId ? ('push-campaign-' + d.campaignId) : 'playjuwa-push',
    renotify: true,
    requireInteraction: true,
    silent: false,
    vibrate: [200, 100, 200]
  };
  return self.registration.showNotification(title, options);
});

/* Pass-through fetch handler — required for Chrome Android installability */
self.addEventListener('fetch', function () {});
`;
  }

  return {
    name: 'firebase-messaging-sw',
    configResolved(config) {
      env = loadEnv(config.mode, config.envDir || config.root, 'VITE_');
    },
    configureServer(server) {
      server.middlewares.use((req, res, next) => {
        if (req.url?.split('?')[0] !== SW_PATH) return next();
        res.setHeader('Content-Type', 'application/javascript; charset=utf-8');
        res.setHeader('Service-Worker-Allowed', '/');
        res.end(buildSwSource(env));
      });
    },
    generateBundle() {
      this.emitFile({
        type: 'asset',
        fileName: 'firebase-messaging-sw.js',
        source: buildSwSource(env)
      });
    }
  };
}
